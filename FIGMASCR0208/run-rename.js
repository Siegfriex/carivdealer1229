// 서브폴더 항목 먼저 처리(루트로 이동), 그 다음 루트 파일 리네이밍
const withSubdir = MAPPING.filter(([cur]) => cur.includes('/'));
const rootOnly = MAPPING.filter(([cur]) => !cur.includes('/'));

function run() {
  let ok = 0, skip = 0, err = 0;
  for (const [cur, neu] of withSubdir) {
    const src = path.join(BASE, cur);
    const dest = path.join(BASE, neu);
    try {
      if (fs.existsSync(src)) {
        fs.renameSync(src, dest);
        console.log('Moved:', cur, '->', neu);
        ok++;
      } else {
        console.warn('Skip (not found):', cur);
        skip++;
      }
    } catch (e) {
      console.error('Error', cur, e.message);
      err++;
    }
  }
  for (const [cur, neu] of rootOnly) {
    const src = path.join(BASE, cur);
    const dest = path.join(BASE, neu);
    try {
      if (fs.existsSync(src)) {
        fs.renameSync(src, dest);
        console.log('Renamed:', cur, '->', neu);
        ok++;
      } else {
        console.warn('Skip (not found):', cur);
        skip++;
      }
    } catch (e) {
      console.error('Error', cur, e.message);
      err++;
    }
  }
  console.log('Done. ok=%d skip=%d err=%d', ok, skip, err);
}

run();
